def repair_reveal_schedule(story_bible_dir: Path) -> dict[str, Any]:
    path = story_bible_dir / "reveal-schedule.yaml"
    loaded = yaml.safe_load(path.read_text(encoding="utf-8")) if path.exists() else {}
    schedule = dict(loaded if isinstance(loaded, dict) else {})
    reveals = schedule.get("reveals")
    if not isinstance(reveals, list):
        reveals = []
    normalized = [item for item in reveals if isinstance(item, dict)]
    by_id = {str(item.get("id") or item.get("reveal_id") or ""): item for item in normalized}
    updated_ids: list[str] = []
    for item in RECOVERY_REVEAL_ITEMS:
        reveal_id = str(item["id"])
        existing = by_id.get(reveal_id)
        if existing is None:
            normalized.append(dict(item))
            updated_ids.append(reveal_id)
            continue
        merged = {**existing, **item}
        existing.clear()
        existing.update(merged)
        updated_ids.append(reveal_id)
    schedule["schema_version"] = schedule.get("schema_version") or "reveal-schedule.v1"
    schedule["reveals"] = normalized
    path.write_text(yaml.safe_dump(schedule, allow_unicode=True, sort_keys=False), encoding="utf-8")
    return {"path": str(path), "managed_reveal_ids": updated_ids}


