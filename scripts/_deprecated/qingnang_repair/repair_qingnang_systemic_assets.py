def repair_kernel_files(story_bible_dir: Path, *, min_bytes: int = MIN_KERNEL_BYTES) -> dict[str, Any]:
    kernels_dir = story_bible_dir / "kernels"
    repaired_files: dict[str, int] = {}
    for path in sorted(kernels_dir.glob("*.json")):
        payload = json.loads(path.read_text(encoding="utf-8"))
        if not isinstance(payload, dict):
            continue
        repaired = _ensure_kernel_minimum(
            path.name,
            repair_kernel_payload(path.name, payload),
            min_bytes=min_bytes,
        )
        text = json.dumps(repaired, ensure_ascii=False, indent=2) + "\n"
        if path.name in KERNEL_REPAIR_CONTRACTS or len(text.encode("utf-8")) < min_bytes:
            path.write_text(text, encoding="utf-8")
            repaired_files[path.name] = path.stat().st_size
    return {"repaired_files": repaired_files}


