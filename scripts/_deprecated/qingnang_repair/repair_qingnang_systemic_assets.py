def _chapter_metadata(package_dir: Path) -> dict[int, dict[str, str]]:
    metadata: dict[int, dict[str, str]] = {}
    for path in sorted(package_dir.glob("chapter-*.md")):
        match = re.search(r"(\d+)", path.stem)
        if match is None:
            continue
        chapter_no = int(match.group(1))
        text = path.read_text(encoding="utf-8")
        heading = next((line.strip("# \t") for line in text.splitlines() if line.startswith("#")), "")
        metadata[chapter_no] = {"title": heading or f"第{chapter_no}章"}
    return metadata


